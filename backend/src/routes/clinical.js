/* ---------------- assessments ---------------- */
const createAssessmentBody = z.object({
  hospitalNumber,
  features: z.record(z.string(), z.union([z.number(), z.string(), z.null()])),
  note: z.string().trim().max(2000).optional(),
});

async function findOrCreatePatient(number, userId) {
  const [existing] = await db.select().from(patients).where(eq(patients.hospitalNumber, number));
  if (existing) return { patient: existing, created: false };
  const [patient] = await db
    .insert(patients)
    .values({ hospitalNumber: number, createdById: userId })
    .onConflictDoNothing()
    .returning();
  if (patient) return { patient, created: true };
  const [raced] = await db.select().from(patients).where(eq(patients.hospitalNumber, number));
  return { patient: raced, created: false };
}

router.post(
  "/assessments",
  requireAuth,
  asyncHandler(async (req, res) => {
    const body = parse(createAssessmentBody, req.body);
    const active = getActiveModel();
    if (!active) throw new HttpError(503, "No active model is available. Contact the administrator.");

    const result = await active.model.assess(body.features); // throws 400 ValidationError

    const { patient, created } = await findOrCreatePatient(body.hospitalNumber, req.user.id);
    if (created) await audit(req, "patient.create", { entityType: "patient", entityId: patient.id });

    const [row] = await db
      .insert(assessments)
      .values({
        patientId: patient.id,
        userId: req.user.id,
        modelVersionId: active.row.id,
        inputFeatures: result.values,
        imputedFeatures: result.imputed,
        warnings: result.warnings,
        explanation: result.explanation,
        prediction: result.prediction,
        probability: result.probability,
        riskBand: result.riskBand,
        clinicianNote: body.note || null,
      })
      .returning();

    await audit(req, "assessment.create", {
      entityType: "assessment",
      entityId: row.id,
      details: { patientId: patient.id, modelVersion: active.row.version, riskBand: row.riskBand },
    });

    // High-risk → queue email alerts (delivered in the background via Resend)
    let alertRecipients = 0;
    if (row.riskBand === "high") {
      try {
        alertRecipients = await enqueueHighRiskAlert({
          assessment: row,
          hospitalNumber: patient.hospitalNumber,
          assessor: req.user,
          modelVersion: active.row.version,
        });
      } catch (err) {
        console.error("[email] Could not queue high-risk alert:", err.message);
      }
    }

    res.status(201).json({
      success: true,
      assessment: { ...row, hospitalNumber: patient.hospitalNumber, modelVersion: active.row.version },
      alertRecipients,
    });
  }),
);

const listQuery = z.object({
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
  patientId: z.string().uuid().optional(),
  mine: z.enum(["true", "false"]).optional(),
  riskBand: z.enum(["low", "moderate", "high"]).optional(),
  from: z.coerce.date().optional(),
  to: z.coerce.date().optional(),
  q: z.string().trim().max(40).optional(),
});

export function assessmentFilters(q, user) {
  const where = [];
  if (q.patientId) where.push(eq(assessments.patientId, q.patientId));
  if (q.mine === "true") where.push(eq(assessments.userId, user.id));
  if (q.riskBand) where.push(eq(assessments.riskBand, q.riskBand));
  if (q.from) where.push(gte(assessments.createdAt, q.from));
  if (q.to) where.push(lte(assessments.createdAt, q.to));
  if (q.q) where.push(ilike(patients.hospitalNumber, `%${q.q}%`));
  return where.length ? and(...where) : undefined;
}

export const assessmentListColumns = {
  id: assessments.id,
  createdAt: assessments.createdAt,
  prediction: assessments.prediction,
  probability: assessments.probability,
  riskBand: assessments.riskBand,
  imputedFeatures: assessments.imputedFeatures,
  patientId: assessments.patientId,
  hospitalNumber: patients.hospitalNumber,
  clinicianName: users.name,
  modelVersion: modelVersions.version,
};

router.get(
  "/assessments",
  requireAuth,
  asyncHandler(async (req, res) => {
    const q = parse(listQuery, req.query);
    const where = assessmentFilters(q, req.user);
    const base = () =>
      db
        .select(assessmentListColumns)
        .from(assessments)
        .innerJoin(patients, eq(assessments.patientId, patients.id))
        .leftJoin(users, eq(assessments.userId, users.id))
        .innerJoin(modelVersions, eq(assessments.modelVersionId, modelVersions.id));

    const [items, [{ total }]] = await Promise.all([
      base().where(where).orderBy(desc(assessments.createdAt)).limit(q.pageSize).offset((q.page - 1) * q.pageSize),
      db
        .select({ total: count() })
        .from(assessments)
        .innerJoin(patients, eq(assessments.patientId, patients.id))
        .where(where),
    ]);
    res.json({ success: true, items, total, page: q.page, pageSize: q.pageSize });
  }),
);

router.get(
  "/assessments/:id",
  requireAuth,
  asyncHandler(async (req, res) => {
    const { id } = parse(uuidParam, req.params);
    const [row] = await db
      .select({
        assessment: assessments,
        hospitalNumber: patients.hospitalNumber,
        clinicianName: users.name,
        clinicianEmail: users.email,
        modelVersion: modelVersions.version,
        manifest: modelVersions.manifest,
      })
      .from(assessments)
      .innerJoin(patients, eq(assessments.patientId, patients.id))
      .leftJoin(users, eq(assessments.userId, users.id))
      .innerJoin(modelVersions, eq(assessments.modelVersionId, modelVersions.id))
      .where(eq(assessments.id, id));
    if (!row) throw new HttpError(404, "Assessment not found.");

    await audit(req, "assessment.view", { entityType: "assessment", entityId: id });

    const alerts = await db
      .select({
        id: emailNotifications.id,
        recipientName: users.name,
        recipientEmail: emailNotifications.recipientEmail,
        status: emailNotifications.status,
        sentAt: emailNotifications.sentAt,
        createdAt: emailNotifications.createdAt,
      })
      .from(emailNotifications)
      .leftJoin(users, eq(emailNotifications.recipientUserId, users.id))
      .where(and(eq(emailNotifications.assessmentId, id), eq(emailNotifications.kind, "high_risk_alert")))
      .orderBy(emailNotifications.createdAt);

    const m = row.manifest;
    res.json({
      success: true,
      assessment: {
        ...row.assessment,
        hospitalNumber: row.hospitalNumber,
        clinicianName: row.clinicianName,
        clinicianEmail: row.clinicianEmail,
        modelVersion: row.modelVersion,
        canEditNote: row.assessment.userId === req.user.id || req.user.role === "admin",
      },
      model: {
        version: m.version,
        features: m.features,
        riskBands: m.risk_bands,
        decisionThreshold: m.decision_threshold,
        metrics: headlineMetrics(m),
      },
      disclaimer: DISCLAIMER,
      alerts,
    });
  }),
);

router.patch(
  "/assessments/:id/note",
  requireAuth,
  asyncHandler(async (req, res) => {
    const { id } = parse(uuidParam, req.params);
    const { note } = parse(z.object({ note: z.string().trim().max(2000) }), req.body);
    const [row] = await db.select({ userId: assessments.userId }).from(assessments).where(eq(assessments.id, id));
    if (!row) throw new HttpError(404, "Assessment not found.");
    if (row.userId !== req.user.id && req.user.role !== "admin") {
      throw new HttpError(403, "Only the clinician who performed the assessment can edit its note.");
    }
    await db.update(assessments).set({ clinicianNote: note || null }).where(eq(assessments.id, id));
    await audit(req, "assessment.note_update", { entityType: "assessment", entityId: id });
    res.json({ success: true });
  }),
);

/* ---------------- patients ---------------- */
router.get(
  "/patients",
  requireAuth,
  asyncHandler(async (req, res) => {
    const q = parse(
      z.object({
        q: z.string().trim().max(40).optional(),
        page: z.coerce.number().int().min(1).default(1),
        pageSize: z.coerce.number().int().min(1).max(100).default(20),
      }),
      req.query,
    );
    const where = q.q ? ilike(patients.hospitalNumber, `%${q.q}%`) : undefined;
    const [items, [{ total }]] = await Promise.all([
      db
        .select({
          id: patients.id,
          hospitalNumber: patients.hospitalNumber,
          createdAt: patients.createdAt,
          assessmentCount: count(assessments.id),
          lastAssessmentAt: max(assessments.createdAt),
        })
        .from(patients)
        .leftJoin(assessments, eq(assessments.patientId, patients.id))
        .where(where)
        .groupBy(patients.id)
        .orderBy(desc(sql`coalesce(max(${assessments.createdAt}), ${patients.createdAt})`))
        .limit(q.pageSize)
        .offset((q.page - 1) * q.pageSize),
      db.select({ total: count() }).from(patients).where(where),
    ]);
    res.json({ success: true, items, total, page: q.page, pageSize: q.pageSize });
  }),
);

router.get(
  "/patients/:id",
  requireAuth,
  asyncHandler(async (req, res) => {
    const { id } = parse(uuidParam, req.params);
    const [patient] = await db.select().from(patients).where(eq(patients.id, id));
    if (!patient) throw new HttpError(404, "Patient not found.");
    const history = await db
      .select(assessmentListColumns)
      .from(assessments)
      .innerJoin(patients, eq(assessments.patientId, patients.id))
      .leftJoin(users, eq(assessments.userId, users.id))
      .innerJoin(modelVersions, eq(assessments.modelVersionId, modelVersions.id))
      .where(eq(assessments.patientId, id))
      .orderBy(desc(assessments.createdAt));
    await audit(req, "patient.view", { entityType: "patient", entityId: id });
    res.json({ success: true, patient, assessments: history });
  }),
);

