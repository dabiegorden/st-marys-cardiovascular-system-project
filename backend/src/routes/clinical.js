const router = express.Router();

const hospitalNumber = z
  .string()
  .trim()
  .min(1, "Hospital number is required.")
  .max(40)
  .regex(/^[A-Za-z0-9/\-_. ]+$/, "Use letters, digits and / - _ . only.")
  .transform((s) => s.toUpperCase());

const uuidParam = z.object({ id: z.string().uuid("Invalid id.") });

export const DISCLAIMER =
  "This result is generated by a machine-learning model to support – not replace – clinical judgement. " +
  "It is not a diagnosis. The model has not been clinically validated at Saint Mary's Hospital, Drobo.";

/** Headline metrics shown to every user next to a result */
export function headlineMetrics(manifest) {
  const pick = (m) =>
    m && {
      n: m.n, accuracy: m.accuracy, precision: m.precision, recall: m.recall,
      specificity: m.specificity, f1: m.f1, roc_auc: m.roc_auc,
    };
  return {
    internal: pick(manifest.evaluation?.internal_test),
    external: (manifest.evaluation?.external ?? []).map((e) => ({ name: e.name, ...pick(e.metrics) })),
  };
}

