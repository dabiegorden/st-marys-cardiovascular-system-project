router.get(
  "/stats/overview",
  requireAuth,
  asyncHandler(async (req, res) => {
    const now = new Date();
    const startOfDay = new Date(now.getFullYear(), now.getMonth(), now.getDate());
    const weekAgo = new Date(now.getTime() - 7 * 864e5);
    const monthAgo = new Date(now.getTime() - 30 * 864e5);
    const startOfYesterday = new Date(startOfDay.getTime() - 864e5);
    const twoWeeksAgo = new Date(now.getTime() - 14 * 864e5);
    const mine = eq(assessments.userId, req.user.id);
    // Counts for "this period vs previous period" comparisons, in one query per scope
    const f = (cond) => sql`count(*) filter (where ${cond})`.mapWith(Number);
    const at = assessments.createdAt;
    const windowCounts = async (scope) => {
      const [r] = await db
        .select({
          today: f(gte(at, startOfDay)),
          yesterday: f(and(gte(at, startOfYesterday), lt(at, startOfDay))),
          week: f(gte(at, weekAgo)),
          prevWeek: f(and(gte(at, twoWeeksAgo), lt(at, weekAgo))),
          highRiskWeek: f(and(gte(at, weekAgo), eq(assessments.riskBand, "high"))),
          highRiskPrevWeek: f(and(gte(at, twoWeeksAgo), lt(at, weekAgo), eq(assessments.riskBand, "high"))),
          total: count(),
        })
        .from(assessments)
        .where(scope);
      return r;
    };

    const personal = await windowCounts(mine);
    const [patientCounts] = await db
      .select({
        total: count(),
        newWeek: sql`count(*) filter (where ${patients.createdAt} >= ${weekAgo})`.mapWith(Number),
        newPrevWeek: sql`count(*) filter (where ${patients.createdAt} >= ${twoWeeksAgo} and ${patients.createdAt} < ${weekAgo})`.mapWith(Number),
      })
      .from(patients);

    const day = sql`date_trunc('day', ${assessments.createdAt})`;
    const daily = await db
      .select({
        day: sql`to_char(${day}, 'YYYY-MM-DD')`,
        total: count(),
        positive: sql`count(*) filter (where ${assessments.prediction} = 1)`.mapWith(Number),
      })
      .from(assessments)
      .where(gte(assessments.createdAt, monthAgo))
      .groupBy(day)
      .orderBy(day);

    const riskDistribution = await db
      .select({ riskBand: assessments.riskBand, total: count() })
      .from(assessments)
      .groupBy(assessments.riskBand);

    const escalationCutoff = new Date(Date.now() - config.followUp.escalationHours * 3600_000);
    const [followUp] = await db
      .select({
        open: sql`count(*) filter (where ${highRiskCases.status} = 'open')`.mapWith(Number),
        active: sql`count(*) filter (where ${highRiskCases.status} <> 'closed')`.mapWith(Number),
        overdue: sql`count(*) filter (where ${highRiskCases.status} = 'open' and ${highRiskCases.createdAt} < ${escalationCutoff})`.mapWith(Number),
        mineActive: sql`count(*) filter (where ${highRiskCases.status} <> 'closed' and ${highRiskCases.assignedToId} = ${req.user.id})`.mapWith(Number),
      })
      .from(highRiskCases);
    const [outcomes] = await db
      .select({
        recorded: sql`count(*) filter (where ${assessments.outcome} is not null)`.mapWith(Number),
        minePending: sql`count(*) filter (where ${assessments.outcome} is null and ${assessments.userId} = ${req.user.id})`.mapWith(Number),
      })
      .from(assessments);

    const out = {
      personal,
      followUp,
      outcomes,
      overall: {
        ...(await windowCounts(undefined)),
        patients: patientCounts.total,
        newPatientsWeek: patientCounts.newWeek,
        newPatientsPrevWeek: patientCounts.newPrevWeek,
        riskDistribution,
        daily,
      },
    };

    if (req.user.role === "admin") {
      const [lastJob] = await db
        .select({ id: trainingJobs.id, status: trainingJobs.status, createdAt: trainingJobs.createdAt, finishedAt: trainingJobs.finishedAt })
        .from(trainingJobs)
        .orderBy(desc(trainingJobs.createdAt))
        .limit(1);
      const userCounts = await db
        .select({ role: users.role, total: count() })
        .from(users)
        .where(sql`coalesce(${users.banned}, false) = false`)
        .groupBy(users.role);
      const active = getActiveModel();
      out.admin = {
        users: userCounts,
        lastTrainingJob: lastJob ?? null,
        activeModel: active && {
          version: active.row.version,
          activatedAt: active.row.activatedAt,
          ...headlineMetrics(active.model.manifest),
        },
      };
    }
    res.json({ success: true, stats: out });
  }),
);

