/** Domains that can never receive mail – sending to them only creates bounces. */
export function isUndeliverableAddress(email) {
  const domain = String(email).split("@")[1]?.toLowerCase() ?? "";
  return !domain || /(^|\.)(local|localhost|test|example|invalid|internal)$/.test(domain) || /^example\.(com|org|net)$/.test(domain);
}

/**
 * Classify a Resend error (the SDK returns { error } instead of throwing).
 * Retry only rate limits, server errors and "concurrent idempotent request";
 * never retry 4xx validation / auth / domain errors (Resend guidance).
 */
export function classifyResendError(error) {
  const status = Number(error?.statusCode ?? error?.status ?? 0);
  const name = String(error?.name ?? "");
  const retryable =
    status === 429 || status >= 500 || status === 0 || name === "concurrent_idempotent_requests" || name === "rate_limit_exceeded" || name === "application_error" || name === "internal_server_error";
  return { retryable, status, message: `${name || "error"}${status ? ` (${status})` : ""}: ${error?.message ?? "Unknown error"}` };
}

