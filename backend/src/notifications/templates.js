export function highRiskAlertEmail({ recipientName, assessment, hospitalNumber, assessorName, modelVersion, appUrl, timezone, showHospitalNumber, reason }) {
  const patientRef = maskHospitalNumber(hospitalNumber, showHospitalNumber);
  const link = `${appUrl}/assessments/${assessment.id}`;
  const when = formatTime(assessment.createdAt, timezone);
  const prob = pctText(assessment.probability);
  const subject = `High-risk CVD assessment – patient ${patientRef} (${prob})`;

  const rowsHtml = `<table role="presentation" width="100%" cellpadding="0" cellspacing="0">
${row("Risk level", `High risk · ${prob} estimated probability`)}
${row("Patient", patientRef)}
${row("Assessed", when)}
${row("Assessed by", assessorName || "Unknown")}
${row("Model", `Random Forest ${modelVersion}`)}
</table>`;

  const html = layout({
    preheader: `High-risk result for patient ${patientRef} – please review.`,
    heading: "High-risk cardiovascular assessment",
    intro: `Hello ${escapeHtml(recipientName || "colleague")}, a new assessment was classified as <strong style="color:#c0262d">high risk</strong>. Please review the patient as soon as possible.`,
    rowsHtml,
    button: { href: link, label: "Open assessment" },
    footer: `${escapeHtml(DISCLAIMER)}<br><br>You receive this because ${escapeHtml(reason)}. You can turn off these emails under Settings. Sign-in is required to view patient details.`,
  });

  const text = [
    "HIGH-RISK CARDIOVASCULAR ASSESSMENT",
    "",
    `Hello ${recipientName || "colleague"},`,
    "A new assessment was classified as HIGH RISK. Please review the patient as soon as possible.",
    "",
    `Risk level:  High risk (${prob})`,
    `Patient:     ${patientRef}`,
    `Assessed:    ${when}`,
    `Assessed by: ${assessorName || "Unknown"}`,
    `Model:       Random Forest ${modelVersion}`,
    "",
    `Open assessment: ${link}`,
    "",
    DISCLAIMER,
    `You receive this because ${reason}. Turn off these emails under Settings.`,
  ].join("\n");

  return { subject, html, text };
}

export function dailyDigestEmail({ recipientName, items, total, appUrl, timezone, showHospitalNumber, periodLabel }) {
  const subject = `Daily CVD summary – ${total} high-risk assessment${total === 1 ? "" : "s"} (${periodLabel})`;
  const shown = items.slice(0, 20);
  const listHtml = `<table role="presentation" width="100%" cellpadding="0" cellspacing="0">
<tr><td style="padding:6px 0;font-size:12px;color:${MUTED};">Time</td><td style="padding:6px 0;font-size:12px;color:${MUTED};">Patient</td><td style="padding:6px 0;font-size:12px;color:${MUTED};text-align:right;">Probability</td><td style="padding:6px 0 6px 12px;font-size:12px;color:${MUTED};">Clinician</td></tr>
${shown
  .map(
    (i) => `<tr>
<td style="padding:8px 0;font-size:13px;border-top:1px solid #f0f0f5;">${escapeHtml(formatTime(i.createdAt, timezone))}</td>
<td style="padding:8px 0;font-size:13px;border-top:1px solid #f0f0f5;"><a href="${escapeHtml(`${appUrl}/assessments/${i.id}`)}" style="color:${BRAND};text-decoration:none;font-weight:600;">${escapeHtml(maskHospitalNumber(i.hospitalNumber, showHospitalNumber))}</a></td>
<td style="padding:8px 0;font-size:13px;text-align:right;border-top:1px solid #f0f0f5;">${escapeHtml(pctText(i.probability))}</td>
<td style="padding:8px 0 8px 12px;font-size:13px;border-top:1px solid #f0f0f5;">${escapeHtml(i.clinicianName || "—")}</td></tr>`,
  )
  .join("\n")}
</table>${total > shown.length ? `<p style="font-size:12px;color:${MUTED};">…and ${total - shown.length} more.</p>` : ""}`;

  const html = layout({
    preheader: `${total} high-risk assessment(s) in the last 24 hours.`,
    heading: "Daily high-risk summary",
    intro: `Hello ${escapeHtml(recipientName || "colleague")}, ${total} assessment${total === 1 ? " was" : "s were"} classified as high risk ${escapeHtml(periodLabel)}. Please make sure each patient has been followed up.`,
    rowsHtml: listHtml,
    button: { href: `${appUrl}/assessments`, label: "Review assessments" },
    footer: `${escapeHtml(DISCLAIMER)}<br><br>Sent to administrators every morning. Turn off under Settings.`,
  });

  const text = [
    "DAILY HIGH-RISK SUMMARY",
    "",
    `${total} assessment(s) classified as high risk ${periodLabel}:`,
    ...shown.map(
      (i) =>
        `- ${formatTime(i.createdAt, timezone)} · ${maskHospitalNumber(i.hospitalNumber, showHospitalNumber)} · ${pctText(i.probability)} · ${i.clinicianName || "—"} · ${appUrl}/assessments/${i.id}`,
    ),
    total > shown.length ? `…and ${total - shown.length} more.` : "",
    "",
    `Review: ${appUrl}/assessments`,
    DISCLAIMER,
  ].join("\n");

  return { subject, html, text };
}

