const row = (label, value) =>
  `<tr><td style="padding:8px 0;font-size:13px;color:${MUTED};width:42%;border-bottom:1px solid #f0f0f5;">${escapeHtml(label)}</td><td style="padding:8px 0;font-size:13px;font-weight:600;color:${INK};border-bottom:1px solid #f0f0f5;">${escapeHtml(value)}</td></tr>`;

const DISCLAIMER =
  "This alert is generated by a decision-support model and is not a diagnosis. Please review the patient and apply clinical judgement.";

