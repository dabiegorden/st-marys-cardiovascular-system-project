/**
 * notifications/templates.js – email content (pure functions, unit-tested)
 * ========================================================================
 * Data protection: emails travel through a third-party provider (Resend), so
 * they carry the minimum needed to act – risk level, time, assessing
 * clinician and a link. No clinical values are included, and the hospital
 * number is masked unless ALERT_SHOW_HOSPITAL_NUMBER=true. The full record
 * opens in the application after sign-in.
 */

const BRAND = "#e2456a";
const INK = "#1f2133";
const MUTED = "#6b6f80";
const CANVAS = "#f4f4f9";

export function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/** "SMH/2026/00412" → "•••0412" (keeps the last 4 characters) */
export function maskHospitalNumber(hn, show = false) {
  if (!hn) return "—";
  if (show) return hn;
  const tail = hn.replace(/\s+/g, "").slice(-4);
  return `•••${tail}`;
}

export const pctText = (p) => (p >= 0.995 ? "> 99%" : p <= 0.005 ? "< 1%" : `${(p * 100).toFixed(1)}%`);

function formatTime(date, timezone) {
  return new Intl.DateTimeFormat("en-GB", {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: timezone,
  }).format(new Date(date));
}

